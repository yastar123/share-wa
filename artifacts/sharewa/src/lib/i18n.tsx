export function translate(language: AppLanguage, key: string, values?: Values): string {
  const adminMessage = language === 'id' ? adminId[key] : language === 'zh' ? adminZh[key] : adminEn[key];
  const message = adminMessage ?? (language === 'id' ? id[key] ?? key : language === 'zh' ? zh[key] ?? key : key);
  return Object.entries(values ?? {}).reduce((text, [name, value]) => text.replaceAll(`{{${name}}}`, String(value)), message);
}

export function translateActivitySummary(language: AppLanguage, summary: string): string {
  const patterns: [RegExp, string][] = [
    [/^Kontak (.+) ditambahkan dengan izin tercatat\.$/, 'Contact {{name}} was added with recorded permission.'],
    [/^Izin (.+) dicatat kembali\.$/, 'Permission for {{name}} was recorded again.'],
    [/^Permintaan opt-out (.+) dicatat\.$/, 'Opt-out request for {{name}} was recorded.'],
    [/^Pesan dikirim kepada (.+)\.$/, 'Message sent to {{name}}.'],
  ];
  for (const [pattern, key] of patterns) {
    const match = summary.match(pattern);
    if (match) return translate(language, key, { name: match[1] });
  }
  return summary;
}

type LanguageContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: string, values?: Values) => string;
};

const LanguageContext = createContext<LanguageContextValue>({
  language: 'id',
  setLanguage: () => undefined,
  t: (key) => key,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    try {
      const saved = window.localStorage.getItem('sharewa-language');
      return saved === 'id' || saved === 'en' || saved === 'zh' ? saved : 'id';
    } catch {
      return 'id';
    }
  });
  const setLanguage = useCallback((next: AppLanguage) => setLanguageState(next), []);

  useEffect(() => {
    try {
      window.localStorage.setItem('sharewa-language', language);
    } catch {
      // The profile remains the durable language preference when storage is unavailable.
    }
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : language;
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values) => translate(language, key, values),
  }), [language, setLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useAppLanguage() {
  return useContext(LanguageContext);
}
